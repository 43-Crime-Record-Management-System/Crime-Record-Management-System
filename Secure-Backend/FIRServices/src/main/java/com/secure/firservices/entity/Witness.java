package com.secure.firservices.entity;
public class Witness {

    private String witnessName;
    private String witnessContactNumber;
    private String witnessStatement;

    public Witness() {}

    public String getWitnessName() { return witnessName; }
    public void setWitnessName(String witnessName) { this.witnessName = witnessName; }

    public String getWitnessContactNumber() { return witnessContactNumber; }
    public void setWitnessContactNumber(String witnessContactNumber) { this.witnessContactNumber = witnessContactNumber; }

    public String getWitnessStatement() { return witnessStatement; }
    public void setWitnessStatement(String witnessStatement) { this.witnessStatement = witnessStatement; }
}

